/// One vertex, mirroring `ugly.slang`'s `VERTEX_STRIDE` byte layout. The shader
/// reads these at hardcoded offsets through a device address, so the layout is
/// frozen below rather than trusted.
#[repr(C)]
#[derive(Clone, Copy, Debug, bytemuck::Pod, bytemuck::Zeroable)]
struct Vertex {
    position: [f32; 3],
    normal: [f32; 3],
}

const _: () = {
    assert!(core::mem::size_of::<Vertex>() == 24);
    assert!(core::mem::offset_of!(Vertex, normal) == 12);
};

/// Where the frame is seen from, on the render side of the membrane.
///
/// Position is absent on purpose: it never crosses. [`Extracted`] arrives
/// already camera-relative, so the eye *is* the origin here and the view matrix
/// carries rotation only — which is what makes a camera 10^12 m out render
/// without jitter (§1.4, §4.2.1).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct View {
    /// Rotation about +Y, radians.
    pub yaw: f32,
    /// Rotation about the camera's right axis, radians.
    pub pitch: f32,
    /// Vertical field of view, radians. Unread while `ortho` is nonzero.
    pub fov_y: f32,
    /// Near plane. With reverse-Z and an infinite far plane this is the *only*
    /// depth-precision knob there is (§2, Math row).
    pub near: f32,
    /// Vertical half-height of an orthographic view, metres — `0.0` renders
    /// perspective (§6 M20). Mirrors [`gg_ecs::boundary::Eye`]'s field of the
    /// same name, and zero-means-perspective is that field's migration
    /// contract, not a convenience.
    pub ortho: f32,
    /// The orthographic far plane, metres. Unread while `ortho` is zero —
    /// perspective's far is at infinity (§2) and a finite far is the price of
    /// parallel rays, paid here and in the frustum's sixth plane.
    pub ortho_far: f32,
    /// Antialias the finished picture (§6 M21) — `r.aa`, which a game's
    /// [`Prefs`](gg_ecs::boundary::Prefs) may override for the player.
    ///
    /// Not camera geometry, and the only field here that is not. It sits here
    /// because a `View` is what a frame is *rendered with* and is rebuilt from
    /// the CVars every frame, which is precisely the plumbing an AA mode needs;
    /// a second parameter on [`Renderer::frame`] would move every call site in
    /// the tree to carry one bool.
    pub aa: bool,
    /// Samples per pixel the scene pass is **asked** for (§6 M21) — `r.msaa`,
    /// which a game's `Prefs` may override for the player.
    ///
    /// A request, not a fact: the renderer clamps it to what the device
    /// advertises and reports the result through [`Renderer::samples`]. Unlike
    /// `aa` this one moves the graph — a count above one allocates a
    /// multisampled scene attachment and a resolve beside it — which is why the
    /// dump shows it and the FXAA flag does not.
    pub samples: Samples,
}

/// The largest count we have that `n` reaches, so a typo'd `r.msaa 3` is 2×
/// rather than off. What a device cannot do is clamped later and *logged*;
/// this one is only about the number the operator typed.
fn asked_samples(n: i64) -> Samples {
    Samples::ALL
        .into_iter()
        .rev()
        .find(|s| i64::from(s.count()) <= n)
        .unwrap_or(Samples::X1)
}

impl Default for View {
    /// Not a constant: `fov_y`, `near`, `ortho_far` and `aa` are CVars (§4.8),
    /// so *rebuilding* a `View` each frame is how a console edit reaches the
    /// screen — and a caller that keeps one instead has pinned them,
    /// deliberately.
    fn default() -> Self {
        View {
            yaw: 0.0,
            pitch: 0.0,
            fov_y: cvars::FOV.float() as f32,
            near: cvars::NEAR.float() as f32,
            ortho: 0.0,
            ortho_far: cvars::ORTHO_FAR.float() as f32,
            aa: cvars::AA.bool(),
            samples: asked_samples(cvars::MSAA.int()),
        }
    }
}

impl View {
    fn rotation(&self) -> render::Quat {
        // YXZ: yaw about world +Y first, then pitch about the rotated right
        // axis — the fly-camera order, and the one that never rolls.
        render::Quat::from_euler(render::EulerRot::YXZ, self.yaw, self.pitch, 0.0)
    }

    /// This view's culling frustum, for the extract stage.
    ///
    /// Built here rather than in `gg-extract` because the projection convention
    /// is this crate's (§2, Math row) and a second construction of it is a
    /// second thing to get subtly wrong. The shell hands the result across,
    /// which is the whole of its part in culling.
    #[must_use]
    pub fn frustum(&self, extent: (u32, u32)) -> Frustum {
        Frustum::from_view_projection(self.view_projection(extent))
    }

    /// How far up-light of this view a shadow caster can sit and still reach a
    /// cascade — what `Extracted::cast_along` sweeps the culling frustum by.
    ///
    /// Public for [`View::frustum`]'s reason: the split scheme is this crate's
    /// (§6 M11), and a shell carrying its own copy of it would decide what to keep
    /// by one rule while the maps recorded by another. Zero is not special —
    /// sweeping by it culls exactly as the view does.
    #[must_use]
    pub fn caster_reach(&self, extent: (u32, u32)) -> f32 {
        lighting::caster_reach(self, extent)
    }

    /// Camera-relative world → clip.
    ///
    /// Public for the same reason [`View::frustum`] is: the convention is this
    /// crate's (§2, Math row), and an instrument that needs to know where a world
    /// point landed in a frame must ask the matrix the frame was drawn with
    /// rather than rebuild one beside it (`gg-tools shadow-sweep`).
    #[must_use]
    pub fn view_projection(&self, extent: (u32, u32)) -> render::Mat4 {
        let rotation = self.rotation();
        let aspect = extent.0.max(1) as f32 / extent.1.max(1) as f32;
        let view = render::camera::rh::view::look_to_mat4(
            render::Vec3::ZERO,
            rotation * render::Vec3::NEG_Z,
            rotation * render::Vec3::Y,
        );
        // The second projection path (§6 M20): both are reverse-Z with the same
        // clear and compare, so the branch ends at the matrix — no pass knows.
        let projection = match self.ortho > 0.0 {
            true => render::orthographic_reverse_z(
                self.ortho * aspect,
                self.ortho,
                self.near,
                self.ortho_far.max(self.near * 2.0),
            ),
            false => render::perspective_reverse_z(self.fov_y, aspect, self.near),
        };
        projection * view
    }
}

/// A window's GPU state and the passes over it — what the shell holds.
///
/// It owns the [`Rhi`] rather than taking one per call so the shell never names
/// `gg-rhi` at all: §3 caps the shell at zero engine logic, and a host that
/// creates pipelines is past that line whatever the line count says.
pub struct Renderer {
    rhi: Rhi,
    pass: BoxPass,
    scene: ScenePass,
    ui: ui::UiPass,
    lighting: lighting::Lighting,
    luminance: luminance::Luminance,
    transients: Transients,
    /// The pack, once a host has named one. `None` is a renderer that draws
    /// boxes and nothing else — which is every tier before M9 and every run
    /// without `--pack`.
    content: Option<Content>,
    /// Where the frame lands in the window. See [`Renderer::set_viewport`].
    viewport: Option<Viewport>,
    /// What the last frame actually rendered at — see [`Renderer::samples`].
    /// Held so the clamp logs when it *changes* rather than every frame.
    samples: Samples,
    /// The dev tier's shader watcher (§4.4); `None` when watching failed.
    #[cfg(feature = "hot-reload")]
    hot: Option<hot::Shaders>,
}

/// `asked` cut to what the device does, announced when the answer changes.
///
/// A free function so both entry points clamp identically; `last` is the
/// caller's memory of the previous answer, which is what keeps a device that
/// cannot do 8× from saying so sixty times a second.
fn granted_samples(report: &DeviceReport, asked: Samples, last: Samples) -> Samples {
    let granted = report.afforded(asked);
    if granted != last {
        match granted == asked {
            true => tracing::info!(samples = granted.count(), "msaa"),
            // The one reduction that is not a refusal (§6 M21), so it says so
            // out loud: an operator reading 8× in a menu and 4× in the log has
            // been told which of the two made the picture.
            false => tracing::warn!(
                asked = asked.count(),
                granted = granted.count(),
                max = report.max_samples().count(),
                "msaa: this device does not do the count asked for"
            ),
        }
    }
    granted
}

impl Renderer {
    /// Bring up the device and swapchain for `window`, and upload the pass.
    ///
    /// # Errors
    ///
    /// Whatever the RHI refuses: no device, no surface, or a failed upload.
    ///
    /// # Safety of teardown
    ///
    /// The surface may not outlive the window it came from, so [`Renderer::shutdown`]
    /// must run while the window is still alive (§4.3).
    pub fn new(
        window: &(impl HasWindowHandle + HasDisplayHandle),
        extent: (u32, u32),
    ) -> Result<Self, RhiError> {
        let mut rhi = Rhi::new(window, extent, wanted_output())?;
        // The display had the last word (§6 M23). Written back rather than
        // remembered, so `r.hdr` reads as what a frame is *actually* encoded
        // into: an operator who asked for HDR10 and reads 0 has been told the
        // monitor, the compositor or the driver declined, and the post pass
        // reads the same number rather than a second copy that could drift.
        let granted = output_index(rhi.output());
        if granted != cvars::HDR.int() {
            tracing::warn!(
                asked = cvars::HDR.int(),
                granted,
                "the surface offered no HDR colour space; output is SDR"
            );
            cvars::HDR.set_int(granted);
        }
        let pass = BoxPass::new(&mut rhi)?;
        let scene = ScenePass::new(&mut rhi)?;
        let ui = ui::UiPass::new(&mut rhi)?;
        let lighting = lighting::Lighting::new(&mut rhi)?;
        let luminance = luminance::Luminance::new(&mut rhi)?;
        Ok(Renderer {
            rhi,
            pass,
            scene,
            ui,
            lighting,
            luminance,
            transients: Transients::default(),
            content: None,
            viewport: None,
            samples: Samples::X1,
            #[cfg(feature = "hot-reload")]
            hot: hot::Shaders::new(),
        })
    }

    /// Map a pack and start its load clock (§4.6). The game names what to draw
    /// out of it; this only says which file.
    ///
    /// # Errors
    /// A file that will not open, or a pack the loader refuses by name.
    pub fn open_pack(&mut self, path: &Path) -> Result<(), ContentError> {
        self.content = Some(Content::open(path)?);
        Ok(())
    }

    /// Instances staged and draws issued by the pack pass last frame (§6 M10).
    ///
    /// Public because "ten thousand objects, four draws" is an exit claim, and a
    /// claim a harness cannot count is a claim nobody checks — `gg-golden`'s
    /// `field` scene asserts on this.
    #[must_use]
    pub fn draw_counts(&self) -> (usize, usize) {
        self.scene.counts()
    }

    /// This frame's luminance histogram, or `None` when `r.histogram` is off
    /// (§6 M11's exit row). Bins are log2 luminance, darkest first.
    ///
    /// Two frames behind on a window and current offscreen — see
    /// [`luminance`](crate::luminance) for why, which is the same reason the
    /// per-pass GPU times beside it are.
    #[must_use]
    pub fn luminance(&self) -> Option<&[u32; luminance::BINS]> {
        self.luminance.bins()
    }

    /// The pack, for a host reporting on its load (§6 M9's exit row).
    #[must_use]
    pub fn pack(&self) -> Option<&Content> {
        self.content.as_ref()
    }

    /// Re-open the pack now if it has been rewritten, rather than waiting for
    /// the frame that would notice (§4.6). `true` if it had been.
    ///
    /// # Errors
    /// A rewritten pack the loader refuses — leaving the old one playing.
    pub fn reload_pack(&mut self) -> Result<bool, ContentError> {
        match &mut self.content {
            Some(content) => content.poll_reload(&mut self.rhi),
            None => Ok(false),
        }
    }

    /// What [`gg_extract::Extracted::append_models`] expands scene assets
    /// through. A renderer with no pack expands nothing, so a host calls this
    /// unconditionally.
    #[must_use]
    pub fn scenes(&self) -> &dyn Scenes {
        match &self.content {
            Some(content) => content,
            None => &(),
        }
    }

    /// Hand the UI pass the coverage atlas its glyphs are cut from (§4.9).
    /// Called once, by whoever owns the font — this side never learns what a
    /// glyph is. Until it is called the UI pass draws nothing.
    ///
    /// # Errors
    ///
    /// A bitmap whose length disagrees with its extent, or an allocation.
    pub fn set_ui_atlas(&mut self, coverage: &ui::Coverage<'_>) -> Result<(), RhiError> {
        self.ui.set_atlas(&mut self.rhi, coverage)
    }

    /// Live buffer and image allocations — the overlay's memory row (§4.8).
    pub fn memory(&self) -> MemoryUse {
        self.rhi.memory()
    }

    /// Which device was chosen, and what it can do (§4.3).
    pub fn device(&self) -> &DeviceReport {
        self.rhi.device_report()
    }

    /// The surface the next frame will present, in physical pixels — the whole
    /// window. What the *game* is composed for is [`Renderer::view_extent`],
    /// which is smaller whenever a viewport is set.
    pub fn extent(&self) -> (u32, u32) {
        self.rhi.swapchain_extent()
    }

    /// Put the game inside `viewport` instead of over the whole window, in
    /// physical pixels from the top-left; `None` restores the whole window.
    ///
    /// This is a **render target and not a crop**: the scene and depth
    /// attachments are allocated at the viewport's size and the projection is
    /// built from its aspect, so an object at the edge of the viewport is at the
    /// edge of the picture. A host that instead let the frame cover the window
    /// and drew panels over it — which is what M15 shipped — is showing the
    /// middle of a frame composed for a wider rectangle, and leaves the
    /// letterbox `gg_ui::Fit` opens at any non-16:9 window showing bare game.
    ///
    /// Sticky, like the pack and the atlas: a shell sets it when the editor
    /// opens and clears it when the editor closes, rather than restating it
    /// every frame. Kept in physical pixels because that is what a scissor is
    /// in — converting canvas units is the caller's, and `gg_editor::viewport`
    /// is where that arithmetic lives.
    pub fn set_viewport(&mut self, viewport: Option<Viewport>) {
        self.viewport = viewport;
    }

    /// The extent the next frame's projection will be built from: the viewport's
    /// when one is set, the surface's otherwise.
    ///
    /// A shell culling against [`View::frustum`] must pass *this*, not
    /// [`Renderer::extent`] — a frustum built from the window while the picture
    /// is composed for a narrower rectangle culls objects that are on screen.
    pub fn view_extent(&self) -> (u32, u32) {
        view_extent(self.viewport, self.rhi.swapchain_extent())
    }

    /// The MSAA count the last frame actually used (§6 M21) — [`View::samples`]
    /// after the device had its say. What a settings menu or an overlay should
    /// show, because it is the count that made the picture.
    pub fn samples(&self) -> Samples {
        self.samples
    }

    /// Clamp and remember, so the warning below fires on a change and not per
    /// frame.
    fn granted(&mut self, asked: Samples) -> Samples {
        self.samples = granted_samples(self.rhi.device_report(), asked, self.samples);
        self.samples
    }

    /// New window size in physical pixels. `(0, 0)` suspends rather than
    /// recreates.
    ///
    /// A viewport set against the old size survives: it is clamped to the
    /// attachment when the frame records (`gg_rhi::Viewport::clamped`), and the
    /// host restates it from the new extent on the tick that follows.
    pub fn resize(&mut self, width: u32, height: u32) {
        self.rhi.resize(width, height);
    }

    /// Per-pass GPU milliseconds from the last retired frame (§4.8) — the rows
    /// the debug overlay draws. Empty in a build without the timestamps, or
    /// before the first frame comes back.
    pub fn pass_timings(&self) -> &[PassTiming] {
        self.rhi.pass_timings()
    }

    /// The device clock, for a profiler anchoring GPU spans to CPU time (§4.8).
    pub fn gpu_clock(&self) -> Option<GpuClock> {
        self.rhi.gpu_clock()
    }

    /// One frame through the graph: depth prepass, forward opaque, post, the UI
    /// layer over it, present.
    ///
    /// `ui` is this frame's whole UI layer as one batch (§4.9) — empty means no
    /// UI pass is declared at all, which is what a dist build with no overlay
    /// hands over every frame.
    ///
    /// # Errors
    ///
    /// Whatever the RHI refuses while compiling, recording, submitting or
    /// presenting.
    pub fn frame(
        &mut self,
        extracted: &Extracted,
        view: &View,
        color: [f32; 4],
        ui: &[ui::UiVertex],
    ) -> Result<FrameOutcome, RhiError> {
        /// Attempts before a frame gives up and leaves the surface to the next
        /// one. Three, because each costs a recreate and the operator's drag is
        /// still moving underneath it — spinning would stall the resize instead
        /// of tracking it.
        const ATTEMPTS: u32 = 3;

        // Between frames is the safe point for a shader swap: the RHI defers
        // pipeline destruction behind the timeline, so in-flight frames finish
        // on the handles they recorded (§4.4).
        #[cfg(feature = "hot-reload")]
        if let Some(hot) = &mut self.hot {
            hot.poll(&mut self.rhi, &mut self.pass, &mut self.scene, &mut self.ui);
        }
        // Before `begin_frame`, not inside it: uploads go to the transfer queue
        // through the staging ring and belong to no frame slot (§4.3). Above the
        // retry as well, so a second attempt re-acquires without re-streaming.
        stream(&mut self.content, &mut self.rhi, extracted)?;
        // An out-of-date acquire is ordinary while a window is being dragged:
        // the surface moves faster than a frame can be built. Retried *here*
        // rather than left to the next frame, because during a Win32 modal
        // resize loop there is no next frame until the operator lets go — a
        // skipped frame is then a window that shows nothing new for the whole
        // drag, which is what the black band trailing the border was (§6 M15.1).
        let mut outcome = FrameOutcome::SkippedOutOfDate;
        for _ in 0..ATTEMPTS {
            outcome = self.frame_once(extracted, view, color, ui)?;
            if !matches!(outcome, FrameOutcome::SkippedOutOfDate) {
                break;
            }
        }
        // Only a presented frame closes the save-to-screen clock: a skipped one
        // put nothing on screen, and reporting it would flatter the budget.
        #[cfg(feature = "hot-reload")]
        if let (Some(hot), FrameOutcome::Presented { .. }) = (&mut self.hot, &outcome) {
            hot.presented();
        }
        Ok(outcome)
    }

    /// One attempt at [`Renderer::frame`]: recreate if due, compile, record,
    /// submit, present. Split out so the retry above re-enters `begin_frame`,
    /// which is the only place the swapchain is rebuilt.
    fn frame_once(
        &mut self,
        extracted: &Extracted,
        view: &View,
        color: [f32; 4],
        ui: &[ui::UiVertex],
    ) -> Result<FrameOutcome, RhiError> {
        gg_core::zone!("render.frame");
        // `begin_frame` is where this slot's previous frame is waited out, so
        // this zone is the pipeline depth showing up as host time — a large one
        // means GPU-bound, not slow.
        let token = {
            gg_core::zone!("render.begin");
            match self.rhi.begin_frame()? {
                FrameStart::Ready(token) => token,
                FrameStart::Skipped(outcome) => return Ok(outcome),
            }
        };
        let extent = token.extent();
        // After `begin_frame`, which is where this slot's previous frame is
        // waited out — the wait that makes writing its region safe. Every pass
        // that stages into a per-slot region has to be on this side of it.
        let slot = GraphContext::frame_slot(&self.rhi);
        // Right after that wait, which is the only synchronization the readback
        // needs: this slot's previous frame has retired, so its luminance grid is
        // on the host side of the copy (§6 M11). Two frames old, exactly like the
        // per-pass GPU times the same panel draws.
        let histogram = luminance::Luminance::enabled();
        match histogram {
            true => self.luminance.read(&self.rhi, slot)?,
            false => self.luminance.clear(),
        }
        // Known before the graph exists, which is what lets the draws carry it:
        // the shadow map's bindless index does not exist until the graph has
        // acquired it, and acquiring it holds the borrow the write would need.
        let frame_address = self.lighting.slot_address(slot);
        // Everything the game is composed for is this, not the window: the
        // projection, the culling frustum the shell already built from
        // `view_extent`, and both attachments below. The window's own extent is
        // left to the two things that really are the window's — the UI layer,
        // and where the post pass puts the result.
        let view_extent = view_extent(self.viewport, extent);
        // After `view_extent`, because a cascade is fitted to the frustum the
        // game is composed for and the window's aspect is not that frustum.
        let sun = {
            gg_core::zone!("render.plan-sun");
            self.lighting.plan(extracted, view, view_extent)
        };
        let cascades = sun.map_or(0, |s| s.cascades().len());
        {
            gg_core::zone!("render.build-boxes");
            self.pass.build(extracted, frame_address);
            self.pass
                .build_shadow(extracted, frame_address, sun.as_ref());
        }
        let content = self.content.as_ref();
        {
            gg_core::zone!("render.build-scene");
            self.scene.build(
                &mut self.rhi,
                slot,
                view_extent,
                extracted,
                view,
                content,
                frame_address,
                cascades,
            )?;
        }
        report_draws(&self.scene, extracted);
        {
            gg_core::zone!("render.build-ui");
            self.ui.write(&mut self.rhi, slot, ui)?;
        }
        let ui_push = self.ui.push(extent);

        // Before the attachments, because the count sizes them — and before the
        // graph takes the RHI, because building a pipeline needs it back.
        let samples = self.granted(view.samples);
        let (at, skybox) = {
            // A lookup after warm-up; a pipeline build on the frame an operator
            // first switches sample counts. Zoned so those two are telling apart.
            gg_core::zone!("render.pipelines");
            let at = (
                self.pass.variant(&mut self.rhi, samples)?,
                self.scene.variant(&mut self.rhi, samples)?,
            );
            (at, self.pass.skybox(&mut self.rhi, samples)?)
        };

        let (mut frame, att) = {
            gg_core::zone!("render.transients");
            let mut frame = self.transients.frame(&mut self.rhi, extent)?;
            let att = scene_attachments(&mut frame, view_extent, sun, histogram, samples)?;
            (frame, att)
        };
        let post_push = self
            .pass
            .post_push(&frame, att.scene, view_extent, view.aa)?;
        let sky = sky_push(view.view_projection(att.view_extent), extracted.sky);
        let sky = sky.as_ref().map(|push| (skybox, push));
        let (draws, ui_draws) = {
            gg_core::zone!("render.draw-lists");
            let draws = SceneDraws::build(&self.pass, &self.scene, &att, &post_push, sky, at);
            let ui_draws: Vec<DrawSpec<'_>> = self.ui.draw(&ui_push).into_iter().collect();
            (draws, ui_draws)
        };
        let luminance = att.grid.map(|grid| {
            (
                grid,
                frame.readback_buffer("render.luminance", self.luminance.buffer(slot)),
            )
        });
        let shadow_slices = draws.shadow_slices();
        // Declared and compiled every frame by design (§4.5) — so this zone is
        // what that design costs, and it grows with the pass count rather than
        // with the scene.
        let declared = {
            gg_core::zone!("render.declare");
            declare_frame(
                &att,
                &draws,
                &shadow_slices,
                &FramePlan {
                    clear: color,
                    viewport: self.viewport,
                    ui: &ui_draws,
                    readback: None,
                    luminance,
                },
            )
        };
        if luminance.is_some() {
            self.luminance.mark(slot);
        }
        let compiled = {
            gg_core::zone!("render.compile");
            frame.compile(&declared)?
        };
        // After `compile`, which is where the graph hands the RHI back — and
        // before `execute`, which is the only thing that lets the GPU see it.
        {
            gg_core::zone!("render.lighting");
            write_lighting(
                &mut self.lighting,
                &mut self.rhi,
                slot,
                view,
                &att,
                extracted,
            )?;
        }
        gg_core::zone!("render.execute");
        self.rhi.execute(token, &compiled.passes())
    }

    /// The graph the next frame will run, as text — `--dump-render-graph`
    /// (§4.5). Compiling it is what the frame does anyway, so what this prints
    /// is what runs.
    ///
    /// # Errors
    ///
    /// Whatever compiling the graph refuses.
    pub fn dump_graph(&mut self) -> Result<String, RhiError> {
        let extent = self.rhi.swapchain_extent();
        // The sun as the *last* frame planned it, like the UI pass below: what
        // the next frame's lights will be is not knowable here.
        let sun = self.lighting.sun();
        let view_extent = view_extent(self.viewport, extent);
        // Before the frame takes the RHI; the buffer below is named, never
        // written — nothing here is submitted.
        let slot = GraphContext::frame_slot(&self.rhi);
        let histogram = luminance::Luminance::enabled();
        // The count the *last* frame was granted, like the sun and the UI pass:
        // a game's `Prefs` may move it, and what the next frame will be asked
        // for is not knowable here. Unlike FXAA — a push constant that moves no
        // edge — MSAA is visible in this dump, as the multisampled attachment
        // and the resolve the forward pass gained.
        let samples = self.samples;
        let at = (
            self.pass.variant(&mut self.rhi, samples)?,
            self.scene.variant(&mut self.rhi, samples)?,
        );
        let skybox = self.pass.skybox(&mut self.rhi, samples)?;
        let mut frame = self.transients.frame(&mut self.rhi, extent)?;
        let att = scene_attachments(&mut frame, view_extent, sun, histogram, samples)?;
        // The CVar rather than a `View` this has none of: FXAA is a push
        // constant, so what it changes is invisible here by construction.
        let post_push = self
            .pass
            .post_push(&frame, att.scene, view_extent, cvars::AA.bool())?;
        // The environment as the last frame was written with, for the sun's
        // reason. The matrix is the identity and that is not a shortcut being
        // taken: nothing here is submitted, so what a dump reports about this
        // draw is that it exists and against which attachment — the push bytes
        // are read by no GPU.
        let sky = sky_push(render::Mat4::IDENTITY, self.lighting.environment());
        let sky = sky.as_ref().map(|push| (skybox, push));
        let draws = SceneDraws::build(&self.pass, &self.scene, &att, &post_push, sky, at);
        // The UI pass as the *last* frame declared it: what the next one draws
        // is not knowable here, and a dump that always omitted it would print a
        // graph the screen never runs.
        let ui_push = self.ui.push(extent);
        let ui_draws: Vec<DrawSpec<'_>> = self.ui.draw(&ui_push).into_iter().collect();
        // Declared but not marked: no submit means no readback to wait on.
        let luminance = att.grid.map(|grid| {
            (
                grid,
                frame.readback_buffer("render.luminance", self.luminance.buffer(slot)),
            )
        });
        let shadow_slices = draws.shadow_slices();
        let declared = declare_frame(
            &att,
            &draws,
            &shadow_slices,
            &FramePlan {
                clear: [0.0; 4],
                viewport: self.viewport,
                ui: &ui_draws,
                readback: None,
                luminance,
            },
        );
        Ok(frame.compile(&declared)?.dump())
    }

    /// Release everything and account for it (§4.3, §5.4).
    pub fn shutdown(mut self) -> ShutdownReport {
        // A refusal here can only be a handle this struct did not issue, which
        // cannot happen — and if it somehow did, the unreleased memory shows up
        // in the report below, which is the check that actually matters.
        drop(self.transients.destroy(&mut self.rhi));
        if let Some(content) = &mut self.content {
            drop(content.destroy(&mut self.rhi));
        }
        drop(self.pass.destroy(&mut self.rhi));
        drop(self.scene.destroy(&mut self.rhi));
        drop(self.ui.destroy(&mut self.rhi));
        drop(self.lighting.destroy(&mut self.rhi));
        drop(self.luminance.destroy(&mut self.rhi));
        self.rhi.shutdown()
    }
}

/// One offscreen frame: the pixels, and the graph that produced them.
pub struct OffscreenFrame {
    /// RGBA8, tightly packed, `extent.0 * extent.1 * 4` bytes.
    pub pixels: Vec<u8>,
    /// The compiled graph as text (§4.5).
    pub dump: String,
    /// The passes handed to the RHI, in submission order — read off the
    /// executed list, not off the declaration, so it cannot drift from it.
    pub order: Vec<String>,
}

/// The v1 pass list with no window in it: the same [`BoxPass`] and the same
/// [`scene_graph`] the shell runs, with §4.5's readback pass appended where the
/// present would be.
///
/// This exists because the shell is windowed and therefore manual (§1.5), which
/// would otherwise leave the engine's own render path with no image coverage at
/// all. `gg-golden` renders through this, so the golden guards the frame the
/// screen gets rather than a lookalike assembled beside it.
pub struct OffscreenRenderer {
    rhi: gg_rhi::OffscreenRhi,
    pass: BoxPass,
    scene: ScenePass,
    ui: ui::UiPass,
    lighting: lighting::Lighting,
    luminance: luminance::Luminance,
    transients: Transients,
    readback: BufferHandle,
    extent: (u32, u32),
    content: Option<Content>,
    viewport: Option<Viewport>,
    /// As [`Renderer::samples`] — see [`OffscreenRenderer::samples`].
    samples: Samples,
    /// As [`Renderer`]'s: here as well because the offscreen path is the only
    /// one an automated gate can drive (§1.5), so it is where the swap is
    /// *proven* — `tests/hot.rs` edits a copied shader tree and reads the new
    /// pixels back.
    #[cfg(feature = "hot-reload")]
    hot: Option<hot::Shaders>,
}

impl OffscreenRenderer {
    /// Bring up a surfaceless device at `extent` and upload the pass.
    ///
    /// # Errors
    ///
    /// Whatever the RHI refuses: no device, or a failed upload.
    pub fn new(extent: (u32, u32)) -> Result<Self, RhiError> {
        // The offscreen target is `Rgba8Srgb` by construction — PNG-ready bytes
        // are the point (§4.10) — so this path has no HDR contract to honour and
        // says so rather than leaving a session's `r.hdr` to encode PQ into it.
        cvars::HDR.set_int(0);
        gg_core::zone!("boot.renderer");
        // The two halves a launch time is actually made of (§6 M25): a device
        // is driver work this process cannot shorten, and pipelines are ours —
        // and the second is the one a warm `gg-cache` is supposed to collapse,
        // which is only checkable if they are separately timed.
        let mut rhi = {
            gg_core::zone!("boot.device");
            gg_rhi::OffscreenRhi::new(extent)?
        };
        gg_core::zone!("boot.pipelines");
        let pass = BoxPass::new(&mut rhi)?;
        let scene = ScenePass::new(&mut rhi)?;
        let ui = ui::UiPass::new(&mut rhi)?;
        let lighting = lighting::Lighting::new(&mut rhi)?;
        let luminance = luminance::Luminance::new(&mut rhi)?;
        // One buffer for the renderer's life: a frame that allocated its own
        // readback would be measuring the allocator as much as the frame.
        let readback = rhi.create_buffer(&BufferDesc {
            name: "render.offscreen.readback",
            size: u64::from(extent.0) * u64::from(extent.1) * 4,
            kind: BufferKind::Readback,
        })?;
        Ok(OffscreenRenderer {
            rhi,
            pass,
            scene,
            ui,
            lighting,
            luminance,
            transients: Transients::default(),
            readback,
            extent,
            content: None,
            viewport: None,
            samples: Samples::X1,
            #[cfg(feature = "hot-reload")]
            hot: hot::Shaders::new(),
        })
    }

    /// Put the frame inside `viewport` — see [`Renderer::set_viewport`].
    ///
    /// Here as well as on the windowed renderer because the windowed one is
    /// manual (§1.5): this is the only path that can prove the composite lands
    /// where it says, in a test with no window in it.
    pub fn set_viewport(&mut self, viewport: Option<Viewport>) {
        self.viewport = viewport;
    }

    /// The extent this renderer's projection is built from — see
    /// [`Renderer::view_extent`].
    #[must_use]
    pub fn view_extent(&self) -> (u32, u32) {
        view_extent(self.viewport, self.extent)
    }

    /// Map a pack — see [`Renderer::open_pack`].
    ///
    /// # Errors
    /// A file that will not open, or a pack the loader refuses by name.
    pub fn open_pack(&mut self, path: &Path) -> Result<(), ContentError> {
        self.content = Some(Content::open(path)?);
        Ok(())
    }

    /// Instances staged and draws issued by the pack pass last frame (§6 M10).
    ///
    /// Public because "ten thousand objects, four draws" is an exit claim, and a
    /// claim a harness cannot count is a claim nobody checks — `gg-golden`'s
    /// `field` scene asserts on this.
    #[must_use]
    pub fn draw_counts(&self) -> (usize, usize) {
        self.scene.counts()
    }

    /// This frame's luminance histogram, or `None` when `r.histogram` is off.
    /// Current rather than two frames behind: an offscreen submit blocks.
    #[must_use]
    pub fn luminance(&self) -> Option<&[u32; luminance::BINS]> {
        self.luminance.bins()
    }

    /// The pack — see [`Renderer::pack`].
    #[must_use]
    pub fn pack(&self) -> Option<&Content> {
        self.content.as_ref()
    }

    /// Re-open a rewritten pack — see [`Renderer::reload_pack`].
    ///
    /// # Errors
    /// A rewritten pack the loader refuses.
    pub fn reload_pack(&mut self) -> Result<bool, ContentError> {
        match &mut self.content {
            Some(content) => content.poll_reload(&mut self.rhi),
            None => Ok(false),
        }
    }

    /// Scene expansion — see [`Renderer::scenes`].
    #[must_use]
    pub fn scenes(&self) -> &dyn Scenes {
        match &self.content {
            Some(content) => content,
            None => &(),
        }
    }

    /// Hand the UI pass its coverage atlas — see [`Renderer::set_ui_atlas`].
    ///
    /// # Errors
    ///
    /// A bitmap whose length disagrees with its extent, or an allocation.
    pub fn set_ui_atlas(&mut self, coverage: &ui::Coverage<'_>) -> Result<(), RhiError> {
        self.ui.set_atlas(&mut self.rhi, coverage)
    }

    /// Live buffer and image allocations (§4.8).
    pub fn memory(&self) -> MemoryUse {
        self.rhi.memory()
    }

    /// Which device was chosen, and what it can do (§4.3).
    pub fn device(&self) -> &DeviceReport {
        self.rhi.device_report()
    }

    /// Per-pass GPU milliseconds from the last [`Self::frame`] (§4.8). Current
    /// rather than a frame behind: an offscreen render blocks until it retires.
    pub fn pass_timings(&self) -> &[PassTiming] {
        self.rhi.pass_timings()
    }

    /// As [`Renderer::samples`]: the count the last frame actually used.
    pub fn samples(&self) -> Samples {
        self.samples
    }

    fn granted(&mut self, asked: Samples) -> Samples {
        self.samples = granted_samples(self.rhi.device_report(), asked, self.samples);
        self.samples
    }

    /// One frame: depth prepass, forward opaque, post, the UI layer, readback.
    ///
    /// # Errors
    ///
    /// Whatever the RHI refuses while compiling, recording or submitting.
    pub fn frame(
        &mut self,
        extracted: &Extracted,
        view: &View,
        color: [f32; 4],
        ui: &[ui::UiVertex],
    ) -> Result<OffscreenFrame, RhiError> {
        // Same point as the windowed frame's poll; with the blocking submit
        // below there is never anything in flight to race the swap.
        #[cfg(feature = "hot-reload")]
        if let Some(hot) = &mut self.hot {
            hot.poll(&mut self.rhi, &mut self.pass, &mut self.scene, &mut self.ui);
        }
        gg_core::zone!("render.frame");
        {
            gg_core::zone!("render.stream");
            stream(&mut self.content, &mut self.rhi, extracted)?;
        }
        // One slot and a blocking submit per frame here, so nothing is in
        // flight to race either write.
        let frame_address = self.lighting.slot_address(0);
        let view_extent = view_extent(self.viewport, self.extent);
        let sun = {
            gg_core::zone!("render.plan-sun");
            self.lighting.plan(extracted, view, view_extent)
        };
        let histogram = luminance::Luminance::enabled();
        let cascades = sun.map_or(0, |s| s.cascades().len());
        {
            gg_core::zone!("render.build-boxes");
            self.pass.build(extracted, frame_address);
            self.pass
                .build_shadow(extracted, frame_address, sun.as_ref());
        }
        let content = self.content.as_ref();
        {
            gg_core::zone!("render.build-scene");
            self.scene.build(
                &mut self.rhi,
                0,
                view_extent,
                extracted,
                view,
                content,
                frame_address,
                cascades,
            )?;
        }
        report_draws(&self.scene, extracted);
        {
            gg_core::zone!("render.build-ui");
            self.ui.write(&mut self.rhi, 0, ui)?;
        }
        let ui_push = self.ui.push(self.extent);
        let samples = self.granted(view.samples);
        let (at, skybox) = {
            gg_core::zone!("render.pipelines");
            let at = (
                self.pass.variant(&mut self.rhi, samples)?,
                self.scene.variant(&mut self.rhi, samples)?,
            );
            (at, self.pass.skybox(&mut self.rhi, samples)?)
        };
        let (mut frame, att) = {
            gg_core::zone!("render.transients");
            let mut frame = self.transients.frame(&mut self.rhi, self.extent)?;
            let att = scene_attachments(&mut frame, view_extent, sun, histogram, samples)?;
            (frame, att)
        };
        let into = frame.readback_buffer("render.offscreen.readback", self.readback);
        let post_push = self
            .pass
            .post_push(&frame, att.scene, view_extent, view.aa)?;
        let sky = sky_push(view.view_projection(att.view_extent), extracted.sky);
        let sky = sky.as_ref().map(|push| (skybox, push));
        let (draws, ui_draws) = {
            gg_core::zone!("render.draw-lists");
            let draws = SceneDraws::build(&self.pass, &self.scene, &att, &post_push, sky, at);
            let ui_draws: Vec<DrawSpec<'_>> = self.ui.draw(&ui_push).into_iter().collect();
            (draws, ui_draws)
        };
        let luminance = att.grid.map(|grid| {
            (
                grid,
                frame.readback_buffer("render.luminance", self.luminance.buffer(0)),
            )
        });
        let shadow_slices = draws.shadow_slices();
        // Declared and compiled every frame by design (§4.5) — so this zone is
        // what that design costs, and it grows with the pass count rather than
        // with the scene.
        let declared = {
            gg_core::zone!("render.declare");
            declare_frame(
                &att,
                &draws,
                &shadow_slices,
                &FramePlan {
                    clear: color,
                    viewport: self.viewport,
                    ui: &ui_draws,
                    readback: Some(into),
                    luminance,
                },
            )
        };
        if luminance.is_some() {
            self.luminance.mark(0);
        }
        let compiled = {
            gg_core::zone!("render.compile");
            frame.compile(&declared)?
        };
        let dump = compiled.dump();
        let passes = compiled.passes();
        let order = passes.iter().map(|p| p.name.to_string()).collect();
        {
            gg_core::zone!("render.lighting");
            write_lighting(&mut self.lighting, &mut self.rhi, 0, view, &att, extracted)?;
        }
        {
            // A blocking submit: record, submit and wait for the device, all
            // inside this one. The offscreen path's own shape, not the shell's.
            gg_core::zone!("render.execute");
            self.rhi.execute(&passes)?;
        }
        // A blocking submit, so unlike the windowed path this is current rather
        // than two frames old.
        match histogram {
            true => self.luminance.read(&self.rhi, 0)?,
            false => self.luminance.clear(),
        }
        // The pixels are on the host, which is this path's "presented".
        #[cfg(feature = "hot-reload")]
        if let Some(hot) = &mut self.hot {
            hot.presented();
        }
        // The copy off the mapped buffer — the cost this path pays and a screen
        // never does, itemised so a reader can subtract it (`gg-golden`'s bench
        // module says the same thing about its CPU number).
        let pixels = {
            gg_core::zone!("render.readback");
            self.rhi.map_buffer(self.readback)?.to_vec()
        };
        Ok(OffscreenFrame {
            pixels,
            dump,
            order,
        })
    }

    /// Release everything and report leaks and validation messages (§4.3).
    pub fn shutdown(mut self) -> ShutdownReport {
        drop(self.transients.destroy(&mut self.rhi));
        drop(self.rhi.destroy_buffer(self.readback));
        if let Some(content) = &mut self.content {
            drop(content.destroy(&mut self.rhi));
        }
        drop(self.pass.destroy(&mut self.rhi));
        drop(self.scene.destroy(&mut self.rhi));
        drop(self.ui.destroy(&mut self.rhi));
        drop(self.lighting.destroy(&mut self.rhi));
        drop(self.luminance.destroy(&mut self.rhi));
        self.rhi.shutdown()
    }
}

/// Ask the pack for what this frame names, and move some of it onto the device.
///
/// Shared by both entry points rather than written twice: a pack that streamed
/// differently offscreen would make the golden suite (§4.10) a gate on a path
/// the screen never takes.
fn stream(
    content: &mut Option<Content>,
    rhi: &mut impl GpuHost,
    extracted: &Extracted,
) -> Result<(), RhiError> {
    let Some(content) = content else {
        return Ok(());
    };
    // Requested from what the frame *shows*, not from a manifest: a scene id
    // pulls its meshes in with it, and an asset nothing draws is never read off
    // the disk at all.
    for instance in &extracted.models {
        content.request(AssetId(instance.asset));
    }
    // The watcher's other end (§4.6). Absent from dist rather than disabled —
    // there is no `ggc` there to rewrite the file.
    #[cfg(feature = "hot-reload")]
    if let Err(refused) = content.poll_reload(rhi) {
        // The old pack is still mapped and still playing; a broken rebuild
        // belongs in the terminal, not in the player's session.
        tracing::error!(error = %refused, "pack reload refused — still drawing the last good one");
    }
    let budget = cvars::UPLOAD_BUDGET.int().max(0) as usize;
    content.pump(rhi, budget)?;
    Ok(())
}

/// One line per frame naming what batching bought: entities extracted, of which
/// culled, staged as instances, issued as draws. On a target of its own and at
/// `debug`, exactly like the per-tick hash (§5.6c) — a human's terminal must not
/// see sixty of these a second, and "ten thousand objects, four draws" is a
/// claim that should be countable rather than asserted (§6 M10).
fn report_draws(scene: &ScenePass, extracted: &Extracted) {
    if tracing::enabled!(target: "gg::draws", tracing::Level::DEBUG) {
        let (instances, draws) = scene.counts();
        tracing::debug!(
            target: "gg::draws",
            models = extracted.models.len(),
            culled = extracted.culled,
            instances,
            draws,
            lights = extracted.lights.len(),
            // The number that explains a corner of a room going dark: extract
            // dropped a light because a cap was reached (§6 M11).
            lights_dropped = extracted.lights_dropped,
        );
    }
}

/// The two pipelines whose shape is the scene pass's sample count, for one
/// count (§6 M21). Copy, so a frame resolves them once and hands them around.
#[derive(Clone, Copy)]
pub(crate) struct Variant {
    pub(crate) prepass: PipelineHandle,
    pub(crate) forward: PipelineHandle,
}

/// Those pipelines, one set per count, created on first ask.
///
/// A set per count rather than a field, because the count is baked into a
/// pipeline at creation and MSAA is a mode an operator switches while the
/// picture is on screen: switching means *another* pipeline, and the one they
/// just left has to still be there when they switch back. At most four sets
/// exist, so this is a short `Vec` and not a map.
#[derive(Default)]
pub(crate) struct Variants {
    live: Vec<(Samples, Variant)>,
}

impl Variants {
    /// The set for `samples`, built from `descs` if this is the first frame to
    /// ask for it. Fallible *here* rather than at the draw, so the lookup a
    /// frame does is infallible and needs no unwrap (§3's lint).
    pub(crate) fn get(
        &mut self,
        rhi: &mut impl GpuHost,
        samples: Samples,
        descs: impl FnOnce(Samples) -> [PipelineDesc<'static>; 2],
    ) -> Result<Variant, RhiError> {
        if let Some((_, variant)) = self.live.iter().find(|(s, _)| *s == samples) {
            return Ok(*variant);
        }
        let [prepass, forward] = descs(samples);
        let prepass = rhi.create_pipeline(&prepass)?;
        // The prepass is orphaned if the forward one fails, so hand it back
        // before the error leaves: a refused mode must cost nothing.
        let forward = match rhi.create_pipeline(&forward) {
            Ok(handle) => handle,
            Err(e) => {
                rhi.destroy_pipeline(prepass)?;
                return Err(e);
            }
        };
        let variant = Variant { prepass, forward };
        self.live.push((samples, variant));
        Ok(variant)
    }

    /// Every live set with its count — what a hot reload has to rebuild, since
    /// an edit to the shared shader invalidates all of them at once.
    #[cfg(feature = "hot-reload")]
    pub(crate) fn each(&mut self) -> impl Iterator<Item = (Samples, &mut Variant)> {
        self.live.iter_mut().map(|(s, v)| (*s, v))
    }

    pub(crate) fn destroy(self, rhi: &mut impl GpuHost) -> Result<(), RhiError> {
        for (_, variant) in self.live {
            rhi.destroy_pipeline(variant.prepass)?;
            rhi.destroy_pipeline(variant.forward)?;
        }
        Ok(())
    }
}

/// The same bookkeeping for a pass whose shape is a sample count but which has
/// only one pipeline — the skybox (§6 M24).
///
/// A second small type rather than making [`Variants`] generic over how many it
/// holds: what a caller wants back is `variant.forward`, and a pipeline set
/// indexed by a number would trade one honest duplication for a convention
/// nobody can read at the call site.
#[derive(Default)]
pub(crate) struct Solo {
    live: Vec<(Samples, PipelineHandle)>,
}

impl Solo {
    pub(crate) fn get(
        &mut self,
        rhi: &mut impl GpuHost,
        samples: Samples,
        desc: impl FnOnce(Samples) -> PipelineDesc<'static>,
    ) -> Result<PipelineHandle, RhiError> {
        if let Some((_, handle)) = self.live.iter().find(|(s, _)| *s == samples) {
            return Ok(*handle);
        }
        let handle = rhi.create_pipeline(&desc(samples))?;
        self.live.push((samples, handle));
        Ok(handle)
    }

    /// Every live pipeline with its count — what a hot reload rebuilds, for
    /// [`Variants::each`]'s reason.
    #[cfg(feature = "hot-reload")]
    pub(crate) fn each(&mut self) -> impl Iterator<Item = (Samples, &mut PipelineHandle)> {
        self.live.iter_mut().map(|(s, h)| (*s, h))
    }

    pub(crate) fn destroy(self, rhi: &mut impl GpuHost) -> Result<(), RhiError> {
        for (_, handle) in self.live {
            rhi.destroy_pipeline(handle)?;
        }
        Ok(())
    }
}

/// Boxes then pack meshes, as one list. Two pipelines inside one pass rather
/// than a pass each: they write the same attachments, so a second prepass would
/// be a second set of derived barriers around no new resource.
fn prepass_draws<'a>(
    pass: &'a BoxPass,
    scene: &'a ScenePass,
    at: (Variant, Variant),
) -> Vec<DrawSpec<'a>> {
    let mut draws = pass.draws(at.0.prepass);
    draws.extend(scene.draws(at.1.prepass));
    draws
}

fn forward_draws<'a>(
    pass: &'a BoxPass,
    scene: &'a ScenePass,
    at: (Variant, Variant),
    sky: Option<(PipelineHandle, &'a skybox_shader::SkyPush)>,
) -> Vec<DrawSpec<'a>> {
    let mut draws = pass.draws(at.0.forward);
    draws.extend(scene.draws(at.1.forward));
    // Last, which is what makes it nearly free: every pixel the scene covers has
    // already failed this draw's depth test (§6 M24, `skybox.slang`).
    draws.extend(sky.map(|(pipeline, push)| DrawSpec {
        pipeline,
        push_constants: bytemuck::bytes_of(push),
        count: FULLSCREEN_VERTICES,
        index_buffer: None,
        indirect: None,
        depth_bias: None,
    }));
    draws
}

/// The environment as the skybox pass reads it, or `None` when the frame has
/// none — which is also what declares the draw out of existence.
///
/// The inverse projection is taken **here**, once per frame on the host, for the
/// reason `skybox.slang` gives: the alternative is the shader rebuilding it from
/// a field of view it would have to be handed, and getting reverse-Z right a
/// second time.
///
/// `Sky::intensity` is folded into the three colours rather than crossing as a
/// fourth number, so the shader is a `lerp` and holds no opinion about scale —
/// the same fold `sky::radiance` performs for the projection, which is what
/// keeps the drawn sky and the lit-by sky the same sky.
fn sky_push(
    view_projection: render::Mat4,
    environment: Option<gg_extract::ExtractedSky>,
) -> Option<skybox_shader::SkyPush> {
    let sky = environment?;
    let colour = |packed| {
        let c = srgb_to_linear(packed);
        let k = sky.intensity.max(0.0);
        [c[0] * k, c[1] * k, c[2] * k, 0.0]
    };
    Some(skybox_shader::SkyPush::new(
        render::rows(view_projection.inverse()),
        colour(sky.zenith),
        colour(sky.horizon),
        colour(sky.ground),
    ))
}

/// Whether `instance` can cast into `cascade`, for a sun travelling along
/// `sun.direction`.
///
/// A **prism** test, not a sphere one, and the extrusion is the whole point: a
/// caster outside the slab but between it and the sun still shadows into it. So
/// the along-light extent is checked separately, against the depth range
/// `lighting::fit` built the projection with, and what is left is a footprint
/// test in the plane perpendicular to the light — where projecting along the sun
/// moves nothing, so a caster's footprint and its shadow's are the same figure.
///
/// That footprint is a **square**, not a disc, and mistaking the two is a real
/// defect rather than a tightness argument: `fit` builds the projection with
/// `orthographic_reverse_z(radius, radius, ..)`, so the slab reaches `radius` up
/// each axis and `radius * sqrt(2)` into its corners. A cull that tested the
/// distance from the slab's axis therefore dropped every caster whose shadow
/// landed in a corner — 21% of each cascade's footprint, and since a cascade is
/// centred on the *view* frustum, a square of missing shadow that slid across
/// the world as the camera turned (`gg-tools shadow-sweep`).
fn casts_into(instance: &Instance, cascade: &lighting::Cascade, sun: &lighting::Sun) -> bool {
    // The diagnostic off switch (`r.shadow_cull 0`): every caster in every
    // cascade, so an artifact that survives it is the fit's and not a cull's.
    if cvars::SHADOW_CULL.int() == 0 {
        return true;
    }
    let to = instance.offset - cascade.centre;
    let along = to.dot(sun.direction);
    // `radius * 2` each way: the eye sits two radii up-light of the centre and
    // the far plane four, so that is exactly the depth the map records.
    if along.abs() > cascade.radius * 2.0 + instance.radius {
        return false;
    }
    // Distance from the *square*, per axis: zero inside it, and the shortest way
    // out of it at a corner. A sphere reaches the slab iff that distance is
    // under its radius.
    let across = to - sun.direction * along;
    let out = |axis: render::Vec3| (across.dot(axis).abs() - cascade.radius).max(0.0);
    let (x, y) = (out(sun.right), out(sun.above));
    x * x + y * y <= instance.radius * instance.radius
}

/// One depth attachment per cascade, or none when nothing casts (§6 M15.3).
///
/// Separate images rather than one array texture, and that is a deliberate line
/// held: a layered attachment would need array layers in `ImageDesc`, per-layer
/// views, and a layer index on the graph's depth binding — RHI surface added for
/// a saving the shadow pass does not get, since the geometry has to be recorded
/// per cascade either way. Four images cost four bindless slots and nothing else.
fn shadow_maps(
    frame: &mut graph::Frame<'_>,
    sun: Option<lighting::Sun>,
) -> Result<Vec<graph::ResourceId>, RhiError> {
    let Some(sun) = sun else {
        return Ok(Vec::new());
    };
    // Named per cascade so a graph dump names what it allocated rather than the
    // same string four times — the dump is read to find out what a frame did.
    const NAMES: [&str; lighting::MAX_CASCADES] = [
        "scene.shadow.0",
        "scene.shadow.1",
        "scene.shadow.2",
        "scene.shadow.3",
    ];
    let extent = (sun.size, sun.size);
    sun.cascades()
        .iter()
        .zip(NAMES)
        .map(|(_, name)| frame.shadow(name, extent))
        .collect()
}

/// The same geometry through the sun's projection. Both pipelines, one pass: a
/// second shadow pass per pass-that-casts would be a second set of derived
/// barriers around one attachment.
///
/// **Unbiased**, and that is the fix rather than an omission (§6 M11's exit
/// row). Rasterizer depth bias corrects the wrong end — it moves the depth the
/// map *records*, so one receiver's bias follows the caster onto every other
/// receiver behind it — and it is not portable: for a float depth attachment the
/// constant term is scaled by an implementation-dependent `r`, which would make
/// a blessed reference (§4.10) a property of the driver. Both jobs are done at
/// the lookup instead, in `include/pbr.slang`.
fn shadow_draws<'a>(pass: &'a BoxPass, scene: &'a ScenePass, cascade: usize) -> Vec<DrawSpec<'a>> {
    let mut draws = pass.shadow_draws(cascade);
    draws.extend(scene.shadow_draws(cascade));
    draws
}

/// Every attachment a frame allocates, and the extent they were sized from.
///
/// `view_extent` rides along rather than being recomputed by each caller: the
/// lighting block's projection has to be the one the attachments and the
/// shell's culling frustum agree on, and the entry points that each picked it
/// by hand had already drifted apart on it.
struct SceneAttachments {
    /// What the projection, the frustum and the scene attachments agree on —
    /// the *viewport's* extent, never the surface's. See [`view_extent`].
    view_extent: (u32, u32),
    backbuffer: graph::ResourceId,
    /// What the post pass samples: the single-sample scene image. Under MSAA
    /// this is the *resolve* target and nothing draws into it directly, which
    /// is why every later pass names this one either way.
    scene: graph::ResourceId,
    /// The multisampled colour the forward pass draws into, when there is one.
    /// Absent at 1× — where `scene` is simply drawn into, and a resolve of an
    /// image to itself would be a pass copying its own output.
    scene_ms: Option<graph::ResourceId>,
    /// The camera's depth, at the same count as `scene_ms`: dynamic rendering
    /// requires every attachment of a pass to agree, and a 1× depth beside a 4×
    /// colour is the mismatch that fails pipeline creation rather than a draw.
    depth: graph::ResourceId,
    /// One per cascade, nearest first; empty when nothing casts (§6 M15.3).
    shadows: Vec<graph::ResourceId>,
    /// `shadows` as bindless slots, for the lighting block.
    shadow_textures: Vec<TextureIndex>,
    /// The luminance target, when `r.histogram` is on (§6 M11).
    grid: Option<graph::ResourceId>,
}

/// Acquire them, in the order the graph dump lists resources.
fn scene_attachments(
    frame: &mut graph::Frame<'_>,
    view_extent: (u32, u32),
    sun: Option<lighting::Sun>,
    histogram: bool,
    samples: Samples,
) -> Result<SceneAttachments, RhiError> {
    let backbuffer = frame.backbuffer();
    // Always allocated, always single-sample, always what is sampled
    // downstream: at 1× the forward pass draws into it, above 1× the resolve
    // lands in it. Everything after the forward pass is then written once.
    let scene = frame.color_at("scene.color", view_extent, SCENE_FORMAT, Samples::X1)?;
    let scene_ms = samples
        .multisampled()
        .then(|| frame.color_at("scene.color.ms", view_extent, SCENE_FORMAT, samples))
        .transpose()?;
    let depth = frame.depth_at("scene.depth", view_extent, samples)?;
    let shadows = shadow_maps(frame, sun)?;
    let shadow_textures = shadows.iter().filter_map(|id| frame.texture(*id)).collect();
    let grid = histogram
        .then(|| frame.color_at("luminance.grid", luminance::GRID, SCENE_FORMAT, Samples::X1))
        .transpose()?;
    Ok(SceneAttachments {
        view_extent,
        backbuffer,
        scene,
        scene_ms,
        depth,
        shadows,
        shadow_textures,
        grid,
    })
}

/// One frame's draw lists. Owned because [`SceneFrame`] and the [`Declared`]s
/// built from it borrow them until the graph is compiled.
struct SceneDraws<'a> {
    prepass: Vec<DrawSpec<'a>>,
    /// One list per cascade, in `shadows` order.
    shadow: Vec<Vec<DrawSpec<'a>>>,
    forward: Vec<DrawSpec<'a>>,
    post: [DrawSpec<'a>; 1],
    /// The luminance resample — the post draw without the curve (§6 M11).
    downsample: [DrawSpec<'a>; 1],
    /// What the post and resample passes sample.
    samples: [graph::ResourceId; 1],
}

impl<'a> SceneDraws<'a> {
    fn build(
        pass: &'a BoxPass,
        scene: &'a ScenePass,
        att: &SceneAttachments,
        post_push: &'a post_shader::PostPush,
        sky: Option<(PipelineHandle, &'a skybox_shader::SkyPush)>,
        at: (Variant, Variant),
    ) -> Self {
        SceneDraws {
            prepass: prepass_draws(pass, scene, at),
            shadow: (0..att.shadows.len())
                .map(|cascade| shadow_draws(pass, scene, cascade))
                .collect(),
            forward: forward_draws(pass, scene, at, sky),
            post: [pass.post_draw(post_push)],
            downsample: [pass.downsample_draw(post_push)],
            samples: [att.scene],
        }
    }

    /// The per-cascade view [`SceneFrame`] takes. Handed back rather than held
    /// because it borrows `self`, and a struct cannot borrow its own field.
    fn shadow_slices(&self) -> Vec<&[DrawSpec<'a>]> {
        self.shadow.iter().map(Vec::as_slice).collect()
    }
}

/// The three things the entry points genuinely differ on, once the graph itself
/// does not.
struct FramePlan<'a> {
    clear: [f32; 4],
    viewport: Option<Viewport>,
    /// Empty declares no UI pass at all.
    ui: &'a [DrawSpec<'a>],
    /// Where the finished backbuffer is copied — the offscreen path's present.
    readback: Option<graph::ResourceId>,
    /// The luminance grid and the buffer it lands in (§6 M11).
    luminance: Option<(graph::ResourceId, graph::ResourceId)>,
}

/// A whole frame in submission order: §4.5's scene graph, the UI layer over it,
/// the readback where a present would be, then the luminance pair.
///
/// One function because the entry points had each assembled this by hand, and
/// hand-copied assembly is what let the projection they lit by diverge from the
/// one their attachments were sized for.
fn declare_frame<'a>(
    att: &'a SceneAttachments,
    draws: &'a SceneDraws<'a>,
    shadow_slices: &'a [&'a [DrawSpec<'a>]],
    plan: &FramePlan<'a>,
) -> Vec<Declared<'a>> {
    let mut declared = scene_graph(&SceneFrame {
        backbuffer: att.backbuffer,
        scene: att.scene,
        scene_ms: att.scene_ms,
        depth: att.depth,
        shadows: &att.shadows,
        clear: plan.clear,
        viewport: plan.viewport,
        prepass_draws: &draws.prepass,
        shadow_draws: shadow_slices,
        forward_draws: &draws.forward,
        post_draws: &draws.post,
        samples: &draws.samples,
        forward_samples: &att.shadows,
    });
    if !plan.ui.is_empty() {
        declared.push(ui_pass(att.backbuffer, plan.ui));
    }
    // After the UI, so the image judged is the one the screen would get (§4.10).
    if let Some(into) = plan.readback {
        declared.push(graph::readback_pass(att.backbuffer, into));
    }
    if let Some((grid, into)) = plan.luminance {
        declared.extend(luminance_passes(
            grid,
            into,
            &draws.samples,
            &draws.downsample,
        ));
    }
    declared
}

/// Stage the lighting block, projected by the extent the attachments were sized
/// from.
///
/// Takes the attachments rather than an extent so there is no second number to
/// pass wrongly: `ugly.slang` reads exactly this matrix for the box prepass and
/// the forward pass, and under a viewport the surface's aspect is not it.
fn write_lighting(
    lighting: &mut lighting::Lighting,
    rhi: &mut impl GpuHost,
    slot: u64,
    view: &View,
    att: &SceneAttachments,
    extracted: &Extracted,
) -> Result<(), RhiError> {
    lighting.write(
        rhi,
        slot,
        view.view_projection(att.view_extent),
        &extracted.lights,
        extracted.sky,
        &att.shadow_textures,
    )
}

/// The boxes, and the four pipelines that draw them: prepass, shadow, forward,
/// post.
struct BoxPass {
    /// Prepass + forward, per sample count (§6 M21).
    variants: Variants,
    /// The environment's, per sample count (§6 M24) — it draws inside the
    /// forward pass, so it is baked against that pass's count like anything
    /// else in it.
    skyboxes: Solo,
    shadow: PipelineHandle,
    post: PipelineHandle,
    /// The luminance resample: the post pass's vertex stage into a small float
    /// target, without the tonemap curve (§6 M11).
    downsample: PipelineHandle,
    vertices: BufferHandle,
    indices: BufferHandle,
    vertex_address: DeviceAddress,
    index_count: u32,
    /// Reused across frames. The push constants have to outlive the [`DrawSpec`]s
    /// that borrow them, and extract already refuses to allocate per frame — a
    /// buffer beside it that did would undo that.
    pushes: Vec<shader::UglyPush>,
    /// One list per cascade, culled — see [`BoxPass::build_shadow`].
    shadow_pushes: Vec<Vec<shader::UglyPush>>,
}

/// The slice of an RHI a pass — or a resident asset — needs to put itself on
/// the GPU.
///
/// The same shape demo 02's `SceneHost` has, and for the same reason: §3 keeps
/// a backend abstraction out of `gg-rhi`, so a crate that wants to run one pass
/// over both entry points writes its own two-line bridge. What it buys here is
/// that the offscreen test builds the *same* pass the shell does, and that
/// [`Residency`](residency::Residency) uploads through the same one.
///
/// Every method forwards verbatim; see the like-named one on
/// [`Rhi`](gg_rhi::Rhi) for what each contracts and refuses.
pub trait GpuHost {
    /// See [`gg_rhi::Rhi::create_buffer`].
    fn create_buffer(&mut self, desc: &BufferDesc<'_>) -> Result<BufferHandle, RhiError>;
    /// See [`gg_rhi::Rhi::upload_buffer`].
    fn upload_buffer(&mut self, h: BufferHandle, offset: u64, b: &[u8]) -> Result<(), RhiError>;
    /// See [`gg_rhi::Rhi::write_buffer`].
    fn write_buffer(&mut self, h: BufferHandle, offset: u64, b: &[u8]) -> Result<(), RhiError>;
    /// See [`gg_rhi::Rhi::flush_uploads`].
    fn flush_uploads(&mut self) -> Result<(), RhiError>;
    /// See [`gg_rhi::Rhi::buffer_address`].
    fn buffer_address(&self, handle: BufferHandle) -> Result<DeviceAddress, RhiError>;
    /// See [`gg_rhi::Rhi::map_buffer`].
    fn map_buffer(&self, handle: BufferHandle) -> Result<&[u8], RhiError>;
    /// See [`gg_rhi::Rhi::create_image`].
    fn create_image(&mut self, desc: &ImageDesc<'_>) -> Result<ImageHandle, RhiError>;
    /// See [`gg_rhi::Rhi::upload_image`].
    fn upload_image(
        &mut self,
        handle: ImageHandle,
        level: u32,
        bytes: &[u8],
    ) -> Result<(), RhiError>;
    /// See [`gg_rhi::Rhi::register_texture`].
    fn register_texture(&mut self, handle: ImageHandle) -> Result<TextureIndex, RhiError>;
    /// See [`gg_rhi::Rhi::create_pipeline`].
    fn create_pipeline(&mut self, desc: &PipelineDesc<'_>) -> Result<PipelineHandle, RhiError>;
    /// See [`gg_rhi::Rhi::destroy_pipeline`].
    fn destroy_pipeline(&mut self, handle: PipelineHandle) -> Result<(), RhiError>;
    /// See [`gg_rhi::Rhi::destroy_buffer`].
    fn destroy_buffer(&mut self, handle: BufferHandle) -> Result<(), RhiError>;
    /// See [`gg_rhi::Rhi::destroy_image`].
    fn destroy_image(&mut self, handle: ImageHandle) -> Result<(), RhiError>;
}

/// Both entry points, verbatim: the trait exists to name the overlap, not to
/// add behaviour to it.
macro_rules! pass_host {
    ($t:ty) => {
        impl GpuHost for $t {
            fn create_buffer(&mut self, desc: &BufferDesc<'_>) -> Result<BufferHandle, RhiError> {
                <$t>::create_buffer(self, desc)
            }
            fn upload_buffer(
                &mut self,
                h: BufferHandle,
                offset: u64,
                b: &[u8],
            ) -> Result<(), RhiError> {
                <$t>::upload_buffer(self, h, offset, b)
            }
            fn write_buffer(
                &mut self,
                h: BufferHandle,
                offset: u64,
                b: &[u8],
            ) -> Result<(), RhiError> {
                <$t>::write_buffer(self, h, offset, b)
            }
            fn flush_uploads(&mut self) -> Result<(), RhiError> {
                <$t>::flush_uploads(self)
            }
            fn buffer_address(&self, handle: BufferHandle) -> Result<DeviceAddress, RhiError> {
                <$t>::buffer_address(self, handle)
            }
            fn map_buffer(&self, handle: BufferHandle) -> Result<&[u8], RhiError> {
                <$t>::map_buffer(self, handle)
            }
            fn create_image(&mut self, desc: &ImageDesc<'_>) -> Result<ImageHandle, RhiError> {
                <$t>::create_image(self, desc)
            }
            fn upload_image(
                &mut self,
                handle: ImageHandle,
                level: u32,
                bytes: &[u8],
            ) -> Result<(), RhiError> {
                <$t>::upload_image(self, handle, level, bytes)
            }
            fn register_texture(&mut self, handle: ImageHandle) -> Result<TextureIndex, RhiError> {
                <$t>::register_texture(self, handle)
            }
            fn create_pipeline(
                &mut self,
                desc: &PipelineDesc<'_>,
            ) -> Result<PipelineHandle, RhiError> {
                <$t>::create_pipeline(self, desc)
            }
            fn destroy_pipeline(&mut self, handle: PipelineHandle) -> Result<(), RhiError> {
                <$t>::destroy_pipeline(self, handle)
            }
            fn destroy_buffer(&mut self, handle: BufferHandle) -> Result<(), RhiError> {
                <$t>::destroy_buffer(self, handle)
            }
            fn destroy_image(&mut self, handle: ImageHandle) -> Result<(), RhiError> {
                <$t>::destroy_image(self, handle)
            }
        }
    };
}

pass_host!(Rhi);
pass_host!(gg_rhi::OffscreenRhi);

impl BoxPass {
    /// Upload the box and build the pipelines. One flush, at startup.
    fn new(rhi: &mut impl GpuHost) -> Result<Self, RhiError> {
        let (vertices, indices) = unit_box();
        let vertex_bytes = bytemuck::cast_slice(&vertices);
        let index_bytes = bytemuck::cast_slice(&indices);

        let vertex_buffer = rhi.create_buffer(&BufferDesc {
            name: "render.box.vertices",
            size: vertex_bytes.len() as u64,
            kind: BufferKind::Storage,
        })?;
        let index_buffer = rhi.create_buffer(&BufferDesc {
            name: "render.box.indices",
            size: index_bytes.len() as u64,
            kind: BufferKind::Index,
        })?;
        rhi.upload_buffer(vertex_buffer, 0, vertex_bytes)?;
        rhi.upload_buffer(index_buffer, 0, index_bytes)?;
        rhi.flush_uploads()?;

        // 1× eagerly, every other count on first ask. Eagerly because 1× is
        // what a session that never opens a video menu draws for its whole
        // life, and building it in the first *frame* instead would move four
        // pipeline creations inside §6 M9's load-to-first-frame budget — which
        // is exactly where GPU-AV's instrumented creation cost blew it.
        let mut variants = Variants::default();
        variants.get(rhi, Samples::X1, |s| [prepass_desc(s), forward_desc(s)])?;
        let mut skyboxes = Solo::default();
        skyboxes.get(rhi, Samples::X1, skybox_desc)?;

        Ok(BoxPass {
            skyboxes,
            variants,
            shadow: rhi.create_pipeline(&shadow_desc())?,
            post: rhi.create_pipeline(&post_desc())?,
            downsample: rhi.create_pipeline(&downsample_desc())?,
            vertices: vertex_buffer,
            indices: index_buffer,
            vertex_address: rhi.buffer_address(vertex_buffer)?,
            index_count: indices.len() as u32,
            pushes: Vec::new(),
            shadow_pushes: Vec::new(),
        })
    }

    /// Rebuild this frame's push constants.
    fn build(&mut self, extracted: &Extracted, frame: DeviceAddress) {
        let address = self.vertex_address;
        self.pushes.clear();
        self.pushes.extend(
            extracted
                .instances
                .iter()
                .map(|instance| push_for(address, frame, instance)),
        );
    }

    /// This frame's shadow pushes: one list per cascade, each holding only the
    /// boxes that can cast *into* that cascade (§6 M15.3).
    ///
    /// The cull is what keeps four cascades from being four times the shadow
    /// pass, and it is [`casts_into`]'s prism rather than a sphere — a caster
    /// outside the slab but between it and the sun still shadows into it.
    fn build_shadow(
        &mut self,
        extracted: &Extracted,
        frame: DeviceAddress,
        sun: Option<&lighting::Sun>,
    ) {
        let address = self.vertex_address;
        let cascades = sun.map_or(&[][..], |s| s.cascades());
        self.shadow_pushes.resize_with(cascades.len(), Vec::new);
        self.shadow_pushes.truncate(cascades.len());
        // Only reachable with cascades to walk, which is the same `Some` the
        // slice came out of — so the loop below never runs without one.
        let Some(sun) = sun else { return };
        for (index, (pushes, cascade)) in self.shadow_pushes.iter_mut().zip(cascades).enumerate() {
            pushes.clear();
            pushes.extend(
                extracted
                    .instances
                    .iter()
                    .filter(|instance| casts_into(instance, cascade, sun))
                    .map(|instance| {
                        let mut push = push_for(address, frame, instance);
                        push.cascade = index as u32;
                        push
                    }),
            );
        }
    }

    /// The boxes that reach cascade `cascade`, through the shadow pipeline.
    fn shadow_draws(&self, cascade: usize) -> Vec<DrawSpec<'_>> {
        let pushes = self
            .shadow_pushes
            .get(cascade)
            .map_or(&[][..], Vec::as_slice);
        self.draws_of(self.shadow, pushes)
    }

    /// The prepass + forward pair for `samples`, built on first ask (§6 M21).
    /// The skybox pipeline for this sample count, built on first ask.
    fn skybox(
        &mut self,
        rhi: &mut impl GpuHost,
        samples: Samples,
    ) -> Result<PipelineHandle, RhiError> {
        self.skyboxes.get(rhi, samples, skybox_desc)
    }

    fn variant(&mut self, rhi: &mut impl GpuHost, samples: Samples) -> Result<Variant, RhiError> {
        self.variants
            .get(rhi, samples, |s| [prepass_desc(s), forward_desc(s)])
    }

    /// The frame's boxes, drawn by `pipeline`.
    ///
    /// A draw call per box, which is the honest cost while the Ugly Game draws
    /// a few hundred; instancing is a §4.6 vertex-format question rather than a
    /// graph one, and it belongs with real meshes.
    fn draws(&self, pipeline: PipelineHandle) -> Vec<DrawSpec<'_>> {
        self.draws_of(pipeline, &self.pushes)
    }

    fn draws_of<'a>(
        &'a self,
        pipeline: PipelineHandle,
        pushes: &'a [shader::UglyPush],
    ) -> Vec<DrawSpec<'a>> {
        pushes
            .iter()
            .map(|push| DrawSpec {
                pipeline,
                push_constants: bytemuck::bytes_of(push),
                count: self.index_count,
                index_buffer: Some(self.indices),
                indirect: None,
                depth_bias: None,
            })
            .collect()
    }

    /// Where the post pass reads the scene attachment from, what exposure it
    /// applies (§6 M11), whether it antialiases on the way out (§6 M21) and how
    /// hard it dithers the quantizer after it (§6 M22).
    ///
    /// The sampler is part of the mode, not a second knob: resolving one texel
    /// per pixel must not filter (a blur nobody asked for), and FXAA's corner
    /// taps sit between texels and are *meant* to be the mean of four.
    fn post_push(
        &self,
        frame: &graph::Frame<'_>,
        scene: graph::ResourceId,
        extent: (u32, u32),
        aa: bool,
    ) -> Result<post_shader::PostPush, RhiError> {
        let index = frame.texture(scene).ok_or_else(|| {
            RhiError::Loader("the scene attachment has no bindless slot to sample".into())
        })?;
        let sampler = match aa {
            true => Sampler::LinearClamp,
            false => Sampler::NearestClamp,
        };
        Ok(post_shader::PostPush::new(
            index.get(),
            sampler.index(),
            cvars::EXPOSURE.float() as f32,
            u32::from(aa),
            // The *source's* texel, so a viewport smaller than the window (the
            // editor's game pane) still steps one scene texel per tap.
            [1.0 / extent.0.max(1) as f32, 1.0 / extent.1.max(1) as f32],
            cvars::DITHER.float() as f32,
            // The granted contract, not the wanted one: `Renderer::new` writes
            // the display's answer back into this CVar before a frame is drawn.
            cvars::HDR.int().clamp(0, 2) as u32,
            cvars::PAPER_WHITE.float().max(1.0) as f32,
            white_point(),
        ))
    }

    fn post_draw<'a>(&self, push: &'a post_shader::PostPush) -> DrawSpec<'a> {
        DrawSpec {
            pipeline: self.post,
            push_constants: bytemuck::bytes_of(push),
            count: FULLSCREEN_VERTICES,
            index_buffer: None,
            indirect: None,
            depth_bias: None,
        }
    }

    /// The luminance resample (§6 M11) — the same fullscreen triangle as the
    /// post pass, into a small float target and without the curve.
    fn downsample_draw<'a>(&self, push: &'a post_shader::PostPush) -> DrawSpec<'a> {
        DrawSpec {
            pipeline: self.downsample,
            push_constants: bytemuck::bytes_of(push),
            count: FULLSCREEN_VERTICES,
            index_buffer: None,
            indirect: None,
            depth_bias: None,
        }
    }

    /// Release the pipelines and both buffers.
    fn destroy(self, rhi: &mut impl GpuHost) -> Result<(), RhiError> {
        rhi.destroy_pipeline(self.downsample)?;
        self.variants.destroy(rhi)?;
        self.skyboxes.destroy(rhi)?;
        rhi.destroy_pipeline(self.shadow)?;
        rhi.destroy_pipeline(self.post)?;
        rhi.destroy_buffer(self.vertices)?;
        rhi.destroy_buffer(self.indices)
    }
}

/// The luminance resample and the copy that brings it back (§6 M11).
///
/// Two passes rather than one because the readback *is* a pass in this graph
/// (§4.5) — which is what gives the copy a derived dependency on the draw
/// instead of a race the frame usually wins.
fn luminance_passes<'a>(
    grid: graph::ResourceId,
    into: graph::ResourceId,
    samples: &'a [graph::ResourceId],
    draws: &'a [DrawSpec<'a>],
) -> [Declared<'a>; 2] {
    [
        Declared {
            name: "luminance",
            body: Body::Draw {
                // `Keep`, like the post pass: a fullscreen triangle writes every
                // texel, so a clear would be a target's worth of thrown-away
                // writes.
                color: Some((grid, Load::Keep)),
                resolve: None,
                depth: None,
                viewport: None,
                samples,
                draws,
            },
        },
        graph::readback_pass(grid, into),
    ]
}

/// The UI layer over a resolved frame: alpha-blended, depth-free, keeping what
/// is already there. Declared as a pass rather than appended to the post pass's
/// draws because it targets a different pipeline state, and because M13's
/// `gg-ui` gets a pass of its own in the graph either way (§4.9).
pub fn ui_pass<'a>(backbuffer: graph::ResourceId, draws: &'a [DrawSpec<'a>]) -> Declared<'a> {
    Declared {
        name: "ui",
        body: Body::Draw {
            color: Some((backbuffer, Load::Keep)),
            resolve: None,
            depth: None,
            // The whole target, never the scene's viewport: the panels that
            // frame a viewport are exactly the pixels outside it (§6 M15).
            viewport: None,
            // The coverage atlas is an uploaded texture like any material's,
            // already in a sampled layout — not a graph resource, so there is
            // no transition for the graph to derive.
            samples: &[],
            draws,
        },
    }
}

/// Everything one frame's [`scene_graph`] needs, gathered so the two entry
/// points assemble it identically. A struct rather than nine arguments because
/// it grew a shadow pass and the next thing to grow it should not have to
/// re-argue the signature.
pub struct SceneFrame<'a> {
    /// Where the frame lands.
    pub backbuffer: graph::ResourceId,
    /// The single-sample HDR scene attachment — what the post pass reads, and
    /// what the forward pass writes when `scene_ms` is absent.
    pub scene: graph::ResourceId,
    /// The multisampled colour the forward pass draws into instead, resolving
    /// into `scene` as the pass ends (§6 M21). `None` is 1× and no resolve.
    pub scene_ms: Option<graph::ResourceId>,
    /// The camera's depth buffer.
    pub depth: graph::ResourceId,
    /// One depth buffer per cascade, nearest first, empty when nothing casts
    /// (§6 M15.3).
    pub shadows: &'a [graph::ResourceId],
    /// Linear clear for the scene attachment.
    pub clear: [f32; 4],
    /// Where the post pass lands the scene in the backbuffer. `None` is all of
    /// it — a window showing nothing but the game. The scene and depth
    /// attachments must already be this size: the viewport crops the *resolve*,
    /// while what makes the picture right for a narrower rectangle is that the
    /// projection was built from its aspect.
    pub viewport: Option<Viewport>,
    /// Depth-prepass draws.
    pub prepass_draws: &'a [DrawSpec<'a>],
    /// Shadow-pass draws, one list per entry in `shadows` and in the same
    /// order. Shorter than `shadows` is a cascade drawn empty, which is a black
    /// map and therefore a fully lit one — not a crash, and not a shadow.
    pub shadow_draws: &'a [&'a [DrawSpec<'a>]],
    /// Forward-pass draws.
    pub forward_draws: &'a [DrawSpec<'a>],
    /// The one fullscreen resolve.
    pub post_draws: &'a [DrawSpec<'a>],
    /// What the post pass samples.
    pub samples: &'a [graph::ResourceId],
    /// What the forward pass samples — the shadow map, when there is one.
    pub forward_samples: &'a [graph::ResourceId],
}

/// The §4.5 v1 scene graph: shadow → depth prepass → forward opaque →
/// fullscreen post.
///
/// A free function rather than a method because it is the *shape*, and the
/// shape is what a second caller wants — the golden harness declares these and
/// appends a readback pass (§4.10), and a shape it had to restate would be a
/// shape that could disagree with the screen's.
///
/// **The shadow pass is declared only when something casts.** A frame with no
/// directional light does not allocate a shadow map, does not clear it and does
/// not name it — so the graph dump is the frame rather than a superset of every
/// frame, and an unlit scene pays nothing for a feature it is not using.
#[must_use]
pub fn scene_graph<'a>(frame: &SceneFrame<'a>) -> Vec<Declared<'a>> {
    let mut declared = Vec::with_capacity(4 + frame.shadows.len());
    // One pass per cascade, nearest first. They are independent — different
    // attachment, different draw list, no read of each other — so the graph's
    // derived barriers put nothing between them.
    const SHADOW_NAMES: [&str; lighting::MAX_CASCADES] =
        ["shadow.0", "shadow.1", "shadow.2", "shadow.3"];
    for ((index, shadow), name) in frame.shadows.iter().enumerate().zip(SHADOW_NAMES) {
        declared.push(Declared {
            name,
            body: Body::Draw {
                color: None,
                resolve: None,
                // Stored, unlike the prepass's: the forward pass samples it.
                depth: Some((*shadow, DepthUse::WriteStore)),
                viewport: None,
                samples: &[],
                draws: frame.shadow_draws.get(index).copied().unwrap_or(&[]),
            },
        });
    }
    declared.push(Declared {
        name: "depth-prepass",
        body: Body::Draw {
            color: None,
            resolve: None,
            depth: Some((frame.depth, DepthUse::WriteStore)),
            // Every pass up to the post owns an attachment sized to the
            // viewport already, so all three draw over the whole of theirs.
            viewport: None,
            samples: &[],
            draws: frame.prepass_draws,
        },
    });
    declared.push(Declared {
        name: "forward-opaque",
        body: Body::Draw {
            // The multisampled attachment when there is one, and `scene` as its
            // resolve — so what the post pass samples is one image under either
            // mode and no pass downstream knows which it got.
            color: Some((
                frame.scene_ms.unwrap_or(frame.scene),
                Load::Clear(frame.clear),
            )),
            resolve: frame.scene_ms.map(|_| frame.scene),
            depth: Some((frame.depth, DepthUse::Test)),
            viewport: None,
            // The shadow map is read through the bindless array like any
            // texture, so the graph would see no dependency at all unless the
            // pass declares it — which is exactly the hazard §4.5 warns that an
            // index hides.
            samples: frame.forward_samples,
            draws: frame.forward_draws,
        },
    });
    declared.push(Declared {
        name: "post",
        body: Body::Draw {
            // `Keep` when the resolve covers the target: the pass writes every
            // pixel of it from a fullscreen triangle, so clearing first would be
            // a full target's worth of writes thrown away. A viewport is exactly
            // the case where that stops being true — the pixels outside it are
            // written by nothing in this graph, and an unwritten backbuffer is
            // whatever the last frame in that slot left there.
            color: Some((
                frame.backbuffer,
                match frame.viewport {
                    Some(_) => Load::Clear(LETTERBOX),
                    None => Load::Keep,
                },
            )),
            // The post pass is single-sample by construction: what it reads is
            // already resolved, and what it writes is the screen.
            resolve: None,
            depth: None,
            viewport: frame.viewport,
            samples: frame.samples,
            draws: frame.post_draws,
        },
    });
    declared
}

/// The extent a frame's projection and attachments are sized from, given the
/// surface it presents into. One function because both renderers and the
/// shell's culling have to agree on it exactly — a frustum and a projection
/// built from different aspects is geometry that pops in at the frame edge.
fn view_extent(viewport: Option<Viewport>, surface: (u32, u32)) -> (u32, u32) {
    match viewport.map(|v| v.clamped(surface)) {
        // A zero-width viewport allocates nothing and draws nothing; the
        // attachment pool refuses a zero extent, so fall back to the surface
        // and let the scissor discard the frame instead.
        Some(v) if v.width > 0 && v.height > 0 => (v.width, v.height),
        _ => surface,
    }
}

/// What surrounds a viewport that does not cover the backbuffer. Opaque black
/// rather than the scene's clear: the border of a composited frame is not more
/// sky, and a host drawing panels over it (§6 M15) covers this anyway.
const LETTERBOX: [f32; 4] = [0.0, 0.0, 0.0, 1.0];

/// The depth prepass: position only, no colour, depth stored for the forward
/// pass to test against.
fn prepass_desc(samples: Samples) -> PipelineDesc<'static> {
    PipelineDesc {
        name: "ugly.prepass",
        vs_spirv: shader::VS_DEPTH_SPIRV,
        vs_entry: shader::VS_DEPTH_ENTRY,
        fs_spirv: shader::FS_DEPTH_SPIRV,
        fs_entry: shader::FS_DEPTH_ENTRY,
        push_constant_size: core::mem::size_of::<shader::UglyPush>() as u32,
        color: ColorTarget::None,
        blend: Blend::Off,
        depth: DepthMode::Write,
        samples,
        depth_bias: false,
    }
}

/// The forward pass, into the scene attachment rather than the backbuffer: the
/// post pass is what reaches the screen. Depth is tested, not written — the
/// prepass placed every fragment already, and reverse-Z's `GREATER_OR_EQUAL`
/// lets the same geometry re-draw exactly where it landed.
fn forward_desc(samples: Samples) -> PipelineDesc<'static> {
    PipelineDesc {
        name: "ugly.forward",
        vs_spirv: shader::VS_MAIN_SPIRV,
        vs_entry: shader::VS_MAIN_ENTRY,
        fs_spirv: shader::FS_MAIN_SPIRV,
        fs_entry: shader::FS_MAIN_ENTRY,
        push_constant_size: core::mem::size_of::<shader::UglyPush>() as u32,
        color: ColorTarget::Format(SCENE_FORMAT),
        blend: Blend::Off,
        depth: DepthMode::TestOnly,
        samples,
        depth_bias: false,
    }
}

/// The environment, drawn last in the forward pass and masked by nothing but
/// the depth test (§6 M24).
///
/// `TestOnly` and a fragment emitted at 0.0: under reverse-Z that is the far
/// plane *and* the clear value, so `GREATER_OR_EQUAL` passes exactly where no
