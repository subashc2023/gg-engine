    /// The whole path with no window in it, through the whole graph: a game
    /// component, extract's narrowing, the push constants, a depth prepass, the
    /// forward pass over its result, the fullscreen resolve, and pixels back
    /// through §4.5's readback pass (§1.5 — the only rendering an automated tier
    /// is allowed to do).
    ///
    /// This is the v1 pass list end to end. The shell runs the same four minus
    /// the readback, and the shell is windowed and therefore manual — so this is
    /// where the derived barriers between prepass, forward and post are proven.
    /// One red box, dead ahead, and a sun to see it by.
    fn one_lit_box(sun: bool) -> Extracted {
        use gg_ecs::World;
        use gg_ecs::boundary::{Light, Renderable};
        use gg_math::sim;

        let mut world = World::new();
        world.register::<Renderable>().unwrap();
        world.register::<Light>().unwrap();
        let entity = world.spawn();
        world
            .insert(
                entity,
                // Dead ahead of an unrotated eye, big enough to cover the middle
                // and small enough to leave the corners clear.
                Renderable::boxed(
                    sim::DVec3::new(0.0, 0.0, -4.0),
                    sim::Vec3::splat(1.0),
                    0x00ff_0000,
                ),
            )
            .unwrap();
        if sun {
            let light = world.spawn();
            world
                .insert(
                    light,
                    // Down and away from the eye, so it lands on the face the
                    // camera sees rather than grazing it.
                    Light::sun(sim::Vec3::new(0.2, -0.4, -1.0), 0x00ff_ffff, 3.0),
                )
                .unwrap();
        }
        let mut extracted = Extracted::default();
        extracted
            .transforms::<Renderable>(&world, sim::DVec3::ZERO, Frustum::UNBOUNDED)
            .unwrap();
        extracted.append_lights(&world).unwrap();
        extracted
    }

    #[test]
    fn the_v1_pass_list_puts_a_declared_box_on_the_target() {
        const EXTENT: (u32, u32) = (64, 64);
        let extracted = one_lit_box(true);

        // Through the public offscreen entry point, not around it: this is the
        // path gg-golden gates on, and a test that assembled the same passes
        // beside it would prove them about itself.
        let mut renderer = OffscreenRenderer::new(EXTENT).unwrap();
        let frame = renderer
            .frame(&extracted, &View::default(), [0.0, 0.0, 0.0, 1.0], &[])
            .unwrap();

        // Every pass the graph derived is a pass the RHI was handed, in the
        // order the dump prints — §6 M6's "matches the executed order", as a
        // machine rather than as a claim about a text file. `order` is read off
        // the executed list, so this is the submission itself.
        assert_eq!(
            frame.order,
            [
                "shadow",
                "depth-prepass",
                "forward-opaque",
                "post",
                "readback",
                "frame-end"
            ]
        );
        for name in &frame.order {
            assert!(
                frame.dump.contains(name.as_str()),
                "the dump names every executed pass: {name}"
            );
        }

        let at = |x: u32, y: u32| {
            let i = ((y * EXTENT.0 + x) * 4) as usize;
            [frame.pixels[i], frame.pixels[i + 1], frame.pixels[i + 2]]
        };
        let middle = at(EXTENT.0 / 2, EXTENT.1 / 2);
        assert!(
            middle[0] > 0x40,
            "the box is there and it is red: {middle:?}"
        );
        // Not "and only red" any more, and that is the milestone rather than a
        // regression: a dielectric's specular highlight is white by
        // construction (§6 M11), so a lit red box has a little of both other
        // channels. What is still true is that red dominates.
        assert!(
            middle[0] > middle[1] * 3 && middle[0] > middle[2] * 3,
            "red still dominates: {middle:?}"
        );
        assert_eq!(at(0, 0), [0, 0, 0], "the corners are still the clear");

        assert!(
            renderer.shutdown().clean(),
            "no leaks, no validation messages"
        );
    }

    /// A frame nothing casts in declares no shadow pass — so the graph is the
    /// frame rather than a superset of every frame, and an unlit scene does not
