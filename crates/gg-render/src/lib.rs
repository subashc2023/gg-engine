    /// implies: the shadow map is rendered from the light, sampled by the
    /// forward pass, and compared the right way round. Reverse-Z means an
    /// inverted comparison shadows exactly what is lit, which is a picture that
    /// still looks like *a* picture — so it is asserted rather than eyeballed.
    #[test]
    fn a_box_over_a_floor_casts_a_shadow_onto_it() {
        use gg_ecs::World;
        use gg_ecs::boundary::{Light, Renderable};
        use gg_math::sim;

        const EXTENT: (u32, u32) = (64, 64);
        let mut world = World::new();
        world.register::<Renderable>().unwrap();
        world.register::<Light>().unwrap();
        let mut spawn = |r: Renderable| {
            let e = world.spawn();
            world.insert(e, r).unwrap();
        };
        // A wide slab whose top face is at y = -1.9, and a box spanning
        // y in [-1, 1] centred ten metres out.
        spawn(Renderable::boxed(
            sim::DVec3::new(0.0, -2.0, -10.0),
            sim::Vec3::new(10.0, 0.1, 10.0),
            0x00ff_ffff,
        ));
        spawn(Renderable::boxed(
            sim::DVec3::new(0.0, 0.0, -10.0),
            sim::Vec3::splat(1.0),
            0x00ff_ffff,
        ));
        let light = world.spawn();
        world
            .insert(
                light,
                // Straight down, so the shadow lands directly beneath the box
                // and the geometry below is arithmetic rather than guesswork.
                Light::sun(sim::Vec3::new(0.0, -1.0, 0.0), 0x00ff_ffff, 2.0),
            )
            .unwrap();

        let mut extracted = Extracted::default();
        extracted
            .transforms::<Renderable>(&world, sim::DVec3::ZERO, Frustum::UNBOUNDED)
            .unwrap();
        extracted.append_lights(&world).unwrap();

        let mut renderer = OffscreenRenderer::new(EXTENT).unwrap();
        let frame = renderer
            .frame(&extracted, &View::default(), [0.0, 0.0, 0.0, 1.0], &[])
            .unwrap();
        let at = |x: u32, y: u32| {
            let i = ((y * EXTENT.0 + x) * 4) as usize;
            u32::from(frame.pixels[i])
        };

        // Row 43 is below the box's silhouette and lands on floor about ten
        // metres out — inside the shadow at the centre column, outside it three
        // metres to the side.
        let shadowed = at(32, 43);
        let lit = at(52, 43);
        assert!(lit > 0x30, "the floor beside the box is lit: {lit}");
        assert!(
            shadowed * 2 < lit,
            "the floor under the box is shadowed: {shadowed} vs {lit}"
        );
        // And not *black*: one cascade with a 3x3 filter still leaves the
        // ambient term, which is what stops a shadow from being a hole.
        assert!(shadowed > 0, "a shadow is dark, not absent: {shadowed}");

        assert!(
            renderer.shutdown().clean(),
            "no leaks, no validation messages"
        );
    }

    /// The luminance histogram measures the frame it was rendered beside.
    ///
    /// Windowed only would have meant windowed only *tested* — and §1.5 means no
    /// automated tier opens a window, so the row would have shipped on a path
    /// nothing ever ran. It is available offscreen for exactly that reason.
    #[test]
    fn the_histogram_bins_the_frame_it_measured() {
        const EXTENT: (u32, u32) = (64, 64);
        // Registered once for the process; other tests in this binary share it.
        static ONCE: std::sync::Once = std::sync::Once::new();
        ONCE.call_once(|| cvars::register().expect("the render knobs are unclaimed"));

        let extracted = one_lit_box(true);
        let mut renderer = OffscreenRenderer::new(EXTENT).unwrap();

        // Off: no pass, no bins, and the graph does not name a grid.
        let frame = renderer
            .frame(&extracted, &View::default(), [0.0, 0.0, 0.0, 1.0], &[])
            .unwrap();
        assert!(renderer.luminance().is_none(), "off by default");
        assert!(!frame.order.iter().any(|name| name == "luminance"));

        cvars::HISTOGRAM.set_bool(true);
        let frame = renderer
            .frame(&extracted, &View::default(), [0.0, 0.0, 0.0, 1.0], &[])
            .unwrap();
        assert!(frame.order.iter().any(|name| name == "luminance"));
        let bins = renderer
            .luminance()
            .expect("a frame measured one")
            .to_owned();
        cvars::HISTOGRAM.reset();

        // Every sampled texel landed in a bucket — the grid is a fixed size, so
        // this is the count and not an estimate.
        let total: u32 = bins.iter().sum();
        assert_eq!(total, luminance::GRID.0 * luminance::GRID.1);
        // The frame is a lit red box on black, so the mass is at both ends: most
        // of the target is the clear, and the box is bright enough to sit above
        // it. A histogram that put everything in one bucket would be a histogram
        // of a constant.
        assert!(bins[0] > 0, "the clear is black: {:?}", &bins[..4]);
        let lit: u32 = bins[1..].iter().sum();
        assert!(lit > 0, "and the box is not: {bins:?}");

        // Turning it off again stops reporting, rather than freezing the last
        // frame's numbers on screen.
        renderer
            .frame(&extracted, &View::default(), [0.0, 0.0, 0.0, 1.0], &[])
            .unwrap();
        assert!(renderer.luminance().is_none(), "and off again");

        assert!(
            renderer.shutdown().clean(),
            "no leaks, no validation messages"
        );
    }

    #[test]
    fn colours_arrive_as_the_game_wrote_them() {
        assert_eq!(srgb_to_linear(0x0000_0000), [0.0, 0.0, 0.0, 1.0]);
        assert_eq!(srgb_to_linear(0x00ff_ffff), [1.0, 1.0, 1.0, 1.0]);
        // Channel order, which is the one thing a swap here would silently
        // survive: pure red stays in the first slot.
        let red = srgb_to_linear(0x00ff_0000);
        assert_eq!((red[0], red[1], red[2]), (1.0, 0.0, 0.0));
        // Mid-grey is where the curve is chosen: squaring 128/255 gives 0.2520,
        // the sRGB EOTF 0.2159. The endpoints agree under either, so only this
        // asserts which one is in use.
        let grey = srgb_to_linear(0x0080_8080);
        assert!((grey[0] - 0.215_860_5).abs() < 1e-6, "{grey:?}");
    }

    #[test]
    // The reference value is computed here and never ships, so §3's ban on
    // `powf` — a portability rule about what crosses the membrane — does not
    // reach it; the table it checks is what ships.
    #[allow(clippy::disallowed_methods)]
    fn the_transfer_function_is_srgb() {
        for (byte, &entry) in SRGB_EOTF.iter().enumerate() {
            let c = byte as f64 / 255.0;
            let reference = if c <= 0.040_45 {
                c / 12.92
            } else {
                ((c + 0.055) / 1.055).powf(2.4)
            } as f32;
            // One ulp at the top of the range: the table is the same formula,
            // and only a differing libm last bit is forgiven.
            assert!(
                (entry - reference).abs() <= f32::EPSILON,
                "byte {byte}: {entry} vs {reference}"
            );
        }
        assert_eq!(SRGB_EOTF[0], 0.0);
        assert_eq!(SRGB_EOTF[255], 1.0);
    }
