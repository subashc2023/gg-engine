/// The graph's scene attachment format. `Rgba16F` since M11: radiance leaves the
/// forward pass unbounded above 1.0 and the tonemapper is what brings it down,
/// so an 8-bit target would clip every highlight before the curve that exists to
/// shape them ever ran. It is also linear, unlike the sRGB target it replaced —
/// the post pass therefore reads exactly what was written and encodes once, on
/// the way to the screen.
const SCENE_FORMAT: ImageFormat = ImageFormat::Rgba16F;

/// The fullscreen triangle the post pass draws — three shader-generated
/// vertices, no buffer.
const FULLSCREEN_VERTICES: u32 = 3;

/// Push constants for one box.
///
/// No matrix: Vulkan guarantees 128 bytes of push and this pass has one push per
/// box, so the object-to-clip product is assembled in the vertex shader from the
/// projection the frame buffer carries. `ugly.slang` states the trade and why
/// the pack pass makes the opposite one.
fn push_for(
    vertices: DeviceAddress,
    frame: DeviceAddress,
    instance: &Instance,
) -> shader::UglyPush {
    shader::UglyPush::new(
        vertices,
        frame,
        srgb_to_linear(instance.color),
        instance.rotation.to_array(),
        instance.offset.extend(0.0).to_array(),
        instance.half_extent.extend(0.0).to_array(),
        // Cascade 0 unless `build_shadow` overwrites it; the forward and prepass
        // pipelines never read the field.
        0,
    )
}

